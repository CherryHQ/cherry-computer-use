#!/usr/bin/env node
// Writes the Linux Wayland helper's third-party notices into THIRD_PARTY_NOTICES.md:
// every crate compiled into the helper on either Linux architecture, with the
// license files it ships (identical texts appear once), and the vendored Hyprland
// protocol. `--check` fails when the file is out of date instead of writing it.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const helper = path.join(root, 'apps/OpenComputerUseLinux/wayland-helper');
const noticesPath = path.join(root, 'THIRD_PARTY_NOTICES.md');
const start = '<!-- wayland-helper-notices:start -->';
const end = '<!-- wayland-helper-notices:end -->';
const targets = ['x86_64-unknown-linux-gnu', 'aarch64-unknown-linux-gnu'];

const cargo = args => execFileSync('cargo', args, { cwd: helper, encoding: 'utf8', maxBuffer: 64 << 20 });
const metadata = JSON.parse(cargo(['metadata', '--locked', '--format-version', '1']));
const byId = new Map(metadata.packages.map(pkg => [`${pkg.name} ${pkg.version}`, pkg]));

// Crates linked into the release binary: normal dependencies only, so build
// scripts and their tools are left out.
const shipped = new Set();
for (const target of targets) {
  for (const line of cargo(['tree', '--locked', '-e', 'normal', '--target', target, '--prefix', 'none', '-f', '{p}']).split('\n')) {
    const [name, version] = line.replace(' (*)', '').trim().split(' ');
    if (name && name !== 'open-computer-use-wayland') shipped.add(`${name} ${version.replace(/^v/, '')}`);
  }
}

const licenseFile = /^(licen[cs]e|copying|notice|unlicense)/i;
const texts = new Map(); // hash -> { text, crates }
const rows = [];
for (const id of [...shipped].sort((a, b) => a.localeCompare(b))) {
  const pkg = byId.get(id);
  if (!pkg) throw new Error(`cargo metadata has no package ${id}`);
  const directory = path.dirname(pkg.manifest_path);
  const files = readdirSync(directory).filter(file => licenseFile.test(file)).sort();
  for (const file of files) {
    const text = readFileSync(path.join(directory, file), 'utf8').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trim();
    const hash = createHash('sha256').update(text).digest('hex');
    if (!texts.has(hash)) texts.set(hash, { text, crates: [] });
    texts.get(hash).crates.push(`${pkg.name} ${pkg.version}`);
  }
  rows.push(`| ${pkg.name} | ${pkg.version} | ${pkg.license ?? pkg.license_file ?? 'unspecified'} |${files.length ? '' : ' no license file in the published crate'}`);
}

const hyprland = readFileSync(path.join(helper, 'protocols/LICENSE.hyprland-protocols'), 'utf8').replace(/[ \t]+$/gm, '').trim();
const section = [
  start,
  '## Linux Wayland helper',
  '',
  'The Linux runtime ships `open-computer-use-wayland`, built from `apps/OpenComputerUseLinux/wayland-helper`. Generated by `scripts/wayland-helper-notices.mjs`; do not edit by hand.',
  '',
  '### Hyprland protocols',
  '',
  'The Hyprland toplevel export protocol is vendored from https://github.com/hyprwm/hyprland-protocols (v0.7.1) and compiled into the helper.',
  '',
  '```text',
  hyprland,
  '```',
  '',
  '### Rust crates',
  '',
  'Where a crate offers a choice of licenses, it is used under any of them; its license files follow the table.',
  '',
  '| Crate | Version | License |',
  '| --- | --- | --- |',
  ...rows,
  '',
  ...[...texts.values()].flatMap(({ text, crates }) => [
    `#### ${crates.join(', ')}`,
    '',
    '```text',
    text.replaceAll('```', "'''"),
    '```',
    '',
  ]),
  end,
].join('\n');

const current = readFileSync(noticesPath, 'utf8');
const startAt = current.indexOf(start);
const next = startAt < 0
  ? `${current.trimEnd()}\n\n${section}\n`
  : `${current.slice(0, startAt)}${section}${current.slice(current.indexOf(end) + end.length)}`;
if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('THIRD_PARTY_NOTICES.md is out of date; run node scripts/wayland-helper-notices.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(noticesPath, next);
  console.log(`Wrote notices for ${rows.length} crates and ${texts.size} license texts.`);
}
